        bool VulkanRenderer::createMeshPipeline()
        {
            // The one storage buffer the vertex shader indexes by draw. The
            // camera rides in push constants instead, because it is the same
            // for every draw in a frame and 116 bytes fits the 128 every
            // implementation guarantees.
            VkDescriptorSetLayoutBinding binding{};
            binding.binding = 0u;
            binding.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
            binding.descriptorCount = 1u;
            binding.stageFlags = VK_SHADER_STAGE_VERTEX_BIT;

            VkDescriptorSetLayoutCreateInfo setLayoutInfo{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
            setLayoutInfo.bindingCount = 1u;
            setLayoutInfo.pBindings = &binding;
            if (!check(vkCreateDescriptorSetLayout(m_device, &setLayoutInfo, nullptr, &m_meshSetLayout),
                       "vkCreateDescriptorSetLayout"))
            {
                return false;
            }

            VkDescriptorPoolSize poolSize{};
            poolSize.type = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
            poolSize.descriptorCount = kFramesInFlight;

            VkDescriptorPoolCreateInfo poolInfo{VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
            poolInfo.maxSets = kFramesInFlight;
            poolInfo.poolSizeCount = 1u;
            poolInfo.pPoolSizes = &poolSize;
            if (!check(vkCreateDescriptorPool(m_device, &poolInfo, nullptr, &m_meshDescriptorPool),
                       "vkCreateDescriptorPool"))
            {
                return false;
            }

            std::array<VkDescriptorSetLayout, kFramesInFlight> layouts{};
            layouts.fill(m_meshSetLayout);
            VkDescriptorSetAllocateInfo setAlloc{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
            setAlloc.descriptorPool = m_meshDescriptorPool;
            setAlloc.descriptorSetCount = kFramesInFlight;
            setAlloc.pSetLayouts = layouts.data();
            if (!check(vkAllocateDescriptorSets(m_device, &setAlloc, m_meshDescriptorSets.data()),
                       "vkAllocateDescriptorSets"))
            {
                return false;
            }

            VkPushConstantRange pushRange{};
            pushRange.stageFlags = VK_SHADER_STAGE_VERTEX_BIT;
            pushRange.offset = 0u;
            pushRange.size = sizeof(MeshPush);

            VkPhysicalDeviceProperties deviceProps{};
            vkGetPhysicalDeviceProperties(m_physicalDevice, &deviceProps);
            if (deviceProps.limits.maxPushConstantsSize < sizeof(MeshPush))
            {
                std::cerr << "[ghpc/vk/mesh] maxPushConstantsSize=" << deviceProps.limits.maxPushConstantsSize
                          << " below the " << sizeof(MeshPush) << " the camera needs" << std::endl;
                return false;
            }

            VkPipelineLayoutCreateInfo layoutInfo{VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO};
            layoutInfo.setLayoutCount = 1u;
            layoutInfo.pSetLayouts = &m_meshSetLayout;
            layoutInfo.pushConstantRangeCount = 1u;
            layoutInfo.pPushConstantRanges = &pushRange;
            if (!check(vkCreatePipelineLayout(m_device, &layoutInfo, nullptr, &m_meshLayout),
                       "vkCreatePipelineLayout"))
            {
                return false;
            }

            // loadOp LOAD and finalLayout TRANSFER_DST_OPTIMAL, so the pass
            // slots into the existing clear-blit-present sequence without
            // moving any of it: the picture is already in the image, and the
            // parity and present barriers after it still see the layout they
            // were written against.
            std::array<VkAttachmentDescription, 2> attachments{};
            attachments[0].format = m_swapchainFormat;
            attachments[0].samples = VK_SAMPLE_COUNT_1_BIT;
            attachments[0].loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
            attachments[0].storeOp = VK_ATTACHMENT_STORE_OP_STORE;
            attachments[0].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
            attachments[0].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
            attachments[0].initialLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
            attachments[0].finalLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;

            attachments[1].format = VK_FORMAT_D32_SFLOAT;
            attachments[1].samples = VK_SAMPLE_COUNT_1_BIT;
            attachments[1].loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
            attachments[1].storeOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
            attachments[1].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
            attachments[1].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
            attachments[1].initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
            attachments[1].finalLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;

            VkAttachmentReference colorRef{0u, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL};
            VkAttachmentReference depthRef{1u, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL};

            VkSubpassDescription subpass{};
            subpass.pipelineBindPoint = VK_PIPELINE_BIND_POINT_GRAPHICS;
            subpass.colorAttachmentCount = 1u;
            subpass.pColorAttachments = &colorRef;
            subpass.pDepthStencilAttachment = &depthRef;

            // The blit before the pass and the readback after it are both
            // transfers, so both edges need a dependency: without them the
            // pass can start before the blit lands, or the readback can run
            // before the pass finishes.
            std::array<VkSubpassDependency, 2> dependencies{};
            dependencies[0].srcSubpass = VK_SUBPASS_EXTERNAL;
            dependencies[0].dstSubpass = 0u;
            dependencies[0].srcStageMask = VK_PIPELINE_STAGE_TRANSFER_BIT;
            dependencies[0].dstStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT |
                                           VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT;
            dependencies[0].srcAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT;
            dependencies[0].dstAccessMask = VK_ACCESS_COLOR_ATTACHMENT_READ_BIT |
                                            VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT |
                                            VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT;

            dependencies[1].srcSubpass = 0u;
            dependencies[1].dstSubpass = VK_SUBPASS_EXTERNAL;
            dependencies[1].srcStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT;
            dependencies[1].dstStageMask = VK_PIPELINE_STAGE_TRANSFER_BIT;
            dependencies[1].srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT;
            dependencies[1].dstAccessMask = VK_ACCESS_TRANSFER_READ_BIT | VK_ACCESS_TRANSFER_WRITE_BIT;

            VkRenderPassCreateInfo passInfo{VK_STRUCTURE_TYPE_RENDER_PASS_CREATE_INFO};
            passInfo.attachmentCount = (uint32_t)attachments.size();
            passInfo.pAttachments = attachments.data();
            passInfo.subpassCount = 1u;
            passInfo.pSubpasses = &subpass;
            passInfo.dependencyCount = (uint32_t)dependencies.size();
            passInfo.pDependencies = dependencies.data();
            if (!check(vkCreateRenderPass(m_device, &passInfo, nullptr, &m_meshPass), "vkCreateRenderPass"))
            {
                return false;
            }

            auto makeModule = [&](const uint32_t *code, size_t bytes, VkShaderModule &out) -> bool {
                VkShaderModuleCreateInfo info{VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO};
                info.codeSize = bytes;
                info.pCode = code;
                return check(vkCreateShaderModule(m_device, &info, nullptr, &out), "vkCreateShaderModule");
            };

            // Kept for the life of the renderer, because pipelines are now
            // created on demand as materials turn up rather than all at once.
            if (!makeModule(kMeshVertSpv, sizeof(kMeshVertSpv), m_meshVertModule) ||
                !makeModule(kMeshFragSpv, sizeof(kMeshFragSpv), m_meshFragModule))
            {
                return false;
            }

            return true;
        }

        VkPipeline VulkanRenderer::pipelineFor(PipelineKey key)
        {
            const uint32_t word = key.word();
            auto it = m_pipelines.find(word);
            if (it != m_pipelines.end())
            {
                return it->second;
            }

            std::array<VkPipelineShaderStageCreateInfo, 2> stages{};
            stages[0] = VkPipelineShaderStageCreateInfo{VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO};
            stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT;
            stages[0].module = m_meshVertModule;
            stages[0].pName = "main";
            stages[1] = VkPipelineShaderStageCreateInfo{VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO};
            stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
            stages[1].module = m_meshFragModule;
            stages[1].pName = "main";

            // ghpc::scene::Vertex, straight from the host mesh cache with no
            // repacking: pos, norm, the four Hmx::Color floats that are bone
            // weights on a skinned mesh, then uv.
            VkVertexInputBindingDescription vertexBinding{};
            vertexBinding.binding = 0u;
            vertexBinding.stride = sizeof(scene::Vertex);
            vertexBinding.inputRate = VK_VERTEX_INPUT_RATE_VERTEX;

            std::array<VkVertexInputAttributeDescription, 4> vertexAttributes{};
            vertexAttributes[0] = {0u, 0u, VK_FORMAT_R32G32B32_SFLOAT, (uint32_t)offsetof(scene::Vertex, pos)};
            vertexAttributes[1] = {1u, 0u, VK_FORMAT_R32G32B32_SFLOAT, (uint32_t)offsetof(scene::Vertex, norm)};
            vertexAttributes[2] = {2u, 0u, VK_FORMAT_R32G32B32A32_SFLOAT, (uint32_t)offsetof(scene::Vertex, weights)};
            vertexAttributes[3] = {3u, 0u, VK_FORMAT_R32G32_SFLOAT, (uint32_t)offsetof(scene::Vertex, uv)};

            VkPipelineVertexInputStateCreateInfo vertexInput{VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO};
            vertexInput.vertexBindingDescriptionCount = 1u;
            vertexInput.pVertexBindingDescriptions = &vertexBinding;
            vertexInput.vertexAttributeDescriptionCount = (uint32_t)vertexAttributes.size();
            vertexInput.pVertexAttributeDescriptions = vertexAttributes.data();

            VkPipelineInputAssemblyStateCreateInfo inputAssembly{VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO};
            inputAssembly.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;

            VkPipelineViewportStateCreateInfo viewportState{VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO};
            viewportState.viewportCount = 1u;
            viewportState.scissorCount = 1u;

            VkPipelineRasterizationStateCreateInfo raster{VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO};
            raster.polygonMode = VK_POLYGON_MODE_FILL;
            // No culling, and that is measured rather than cautious: there is
            // no backface cull anywhere in VU1's 13,872 bytes
            // (evidence/2026-09-19-vu1-tl-semantics.md), so culling here would
            // delete geometry the PS2 draws.
            raster.cullMode = VK_CULL_MODE_NONE;
            raster.frontFace = VK_FRONT_FACE_COUNTER_CLOCKWISE;
            raster.lineWidth = 1.0f;

            VkPipelineMultisampleStateCreateInfo multisample{VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO};
            multisample.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;

            // The GS test, mapped through the shader's sense of depth: GS z is
            // 29490.8 * (1 - clip.z/w), so it counts up towards the viewer and
            // the buffer clears to zero rather than one. GEQUAL and GREATER
            // therefore stay GEQUAL and GREATER rather than inverting.
            //
            // ZTE clear means no test, and Vulkan ties depth writes to
            // depthTestEnable, so that case is an ALWAYS test rather than a
            // disabled one: disabling it would silently drop the write that
            // ZMSK still asks for.
            VkCompareOp compare = VK_COMPARE_OP_GREATER_OR_EQUAL;
            switch (key.ztst)
            {
            case 0u:
                compare = VK_COMPARE_OP_NEVER;
                break;
            case 1u:
                compare = VK_COMPARE_OP_ALWAYS;
                break;
            case 3u:
                compare = VK_COMPARE_OP_GREATER;
                break;
            default:
                compare = VK_COMPARE_OP_GREATER_OR_EQUAL;
                break;
            }
            if (!key.depthTest)
            {
                compare = VK_COMPARE_OP_ALWAYS;
            }
            bool depthWrite = key.depthWrite != 0u;

            // Everything above reads the material. Only mode 3 keeps it; see
            // the m_depthMode note for the coverage numbers that put the
            // forced mode in front.
            switch (m_depthMode)
            {
            case 0:
                compare = VK_COMPARE_OP_ALWAYS;
                depthWrite = false;
                break;
            case 2:
                compare = VK_COMPARE_OP_LESS;
                depthWrite = true;
                break;
            case 3:
                break;
            default:
                compare = VK_COMPARE_OP_GREATER;
                depthWrite = true;
                break;
            }

            VkPipelineDepthStencilStateCreateInfo depthStencil{VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO};
            depthStencil.depthTestEnable = VK_TRUE;
            depthStencil.depthWriteEnable = depthWrite ? VK_TRUE : VK_FALSE;
            depthStencil.depthCompareOp = compare;

            // What this pipeline actually got, printed once per created
            // pipeline. There are at most 32 of them, so this is not a hot
            // path, and it is the only way to tell "the knob had no effect"
            // apart from "the knob had an effect that did not change the
            // picture". Two arms that differed only in GHPC_VK_MESH_DEPTH
            // produced the same coverage, and an outcome number cannot say
            // which of those it was.
            std::fprintf(stderr,
                         "[ghpc/vk/pipeline] word=%u ztst=%u zte=%u zmsk=%u blend=%u"
                         " depthMode=%d compare=%d write=%d\n",
                         word, (unsigned)key.ztst, (unsigned)key.depthTest,
                         (unsigned)(key.depthWrite ? 0u : 1u), (unsigned)key.blend,
                         m_depthMode, (int)compare, depthWrite ? 1 : 0);

            // Source alpha over destination, which is what mBlend's non-opaque
            // modes amount to. The exact equation is in ALPHA_1 at
            // PsMat+0x138 and honouring all of it is still ahead; what matters
            // here is that a blended draw stops writing an opaque rectangle
            // over the frame.
            VkPipelineColorBlendAttachmentState blendAttachment{};
            blendAttachment.blendEnable = key.blend ? VK_TRUE : VK_FALSE;
            blendAttachment.srcColorBlendFactor = VK_BLEND_FACTOR_SRC_ALPHA;
            blendAttachment.dstColorBlendFactor = VK_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA;
            blendAttachment.colorBlendOp = VK_BLEND_OP_ADD;
            blendAttachment.srcAlphaBlendFactor = VK_BLEND_FACTOR_ONE;
            blendAttachment.dstAlphaBlendFactor = VK_BLEND_FACTOR_ZERO;
            blendAttachment.alphaBlendOp = VK_BLEND_OP_ADD;
            blendAttachment.colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT |
                                             VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;

            VkPipelineColorBlendStateCreateInfo blend{VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO};
            blend.attachmentCount = 1u;
            blend.pAttachments = &blendAttachment;

            const std::array<VkDynamicState, 2> dynamicStates{VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR};
            VkPipelineDynamicStateCreateInfo dynamic{VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO};
            dynamic.dynamicStateCount = (uint32_t)dynamicStates.size();
            dynamic.pDynamicStates = dynamicStates.data();

            VkGraphicsPipelineCreateInfo pipelineInfo{VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO};
            pipelineInfo.stageCount = (uint32_t)stages.size();
            pipelineInfo.pStages = stages.data();
            pipelineInfo.pVertexInputState = &vertexInput;
            pipelineInfo.pInputAssemblyState = &inputAssembly;
            pipelineInfo.pViewportState = &viewportState;
            pipelineInfo.pRasterizationState = &raster;
            pipelineInfo.pMultisampleState = &multisample;
            pipelineInfo.pDepthStencilState = &depthStencil;
            pipelineInfo.pColorBlendState = &blend;
            pipelineInfo.pDynamicState = &dynamic;
            pipelineInfo.layout = m_meshLayout;
            pipelineInfo.renderPass = m_meshPass;
            pipelineInfo.subpass = 0u;

            VkPipeline pipeline = VK_NULL_HANDLE;
            if (!check(vkCreateGraphicsPipelines(m_device, VK_NULL_HANDLE, 1u, &pipelineInfo,
                                                 nullptr, &pipeline),
                       "vkCreateGraphicsPipelines"))
            {
                pipeline = VK_NULL_HANDLE;
            }

            // Cached either way. A null entry is a state this device refused,
            // and retrying it every draw of every frame would turn one failure
            // into a stall.
            m_pipelines.emplace(word, pipeline);
            return pipeline;
        }

        void VulkanRenderer::destroyMeshPipeline()
        {
            destroyMeshTargets();

            for (uint32_t i = 0u; i < kFramesInFlight; ++i)
            {
                if (m_drawMapped[i] != nullptr)
                {
                    vkUnmapMemory(m_device, m_drawMemories[i]);
                    m_drawMapped[i] = nullptr;
                }
                if (m_drawBuffers[i] != VK_NULL_HANDLE)
                {
                    vkDestroyBuffer(m_device, m_drawBuffers[i], nullptr);
                    m_drawBuffers[i] = VK_NULL_HANDLE;
                }
                if (m_drawMemories[i] != VK_NULL_HANDLE)
                {
                    vkFreeMemory(m_device, m_drawMemories[i], nullptr);
                    m_drawMemories[i] = VK_NULL_HANDLE;
                }
                m_drawCapacities[i] = 0u;
            }

            for (auto &entry : m_meshCache)
            {
                MeshBuffers &m = entry.second;
                if (m.vertexBuffer != VK_NULL_HANDLE)
                {
                    vkDestroyBuffer(m_device, m.vertexBuffer, nullptr);
                }
                if (m.vertexMemory != VK_NULL_HANDLE)
                {
                    vkFreeMemory(m_device, m.vertexMemory, nullptr);
                }
                if (m.indexBuffer != VK_NULL_HANDLE)
                {
                    vkDestroyBuffer(m_device, m.indexBuffer, nullptr);
                }
                if (m.indexMemory != VK_NULL_HANDLE)
                {
                    vkFreeMemory(m_device, m.indexMemory, nullptr);
                }
            }
            m_meshCache.clear();

            for (auto &entry : m_pipelines)
            {
                if (entry.second != VK_NULL_HANDLE)
                {
                    vkDestroyPipeline(m_device, entry.second, nullptr);
                }
            }
            m_pipelines.clear();

            if (m_meshVertModule != VK_NULL_HANDLE)
            {
                vkDestroyShaderModule(m_device, m_meshVertModule, nullptr);
                m_meshVertModule = VK_NULL_HANDLE;
            }
            if (m_meshFragModule != VK_NULL_HANDLE)
            {
                vkDestroyShaderModule(m_device, m_meshFragModule, nullptr);
                m_meshFragModule = VK_NULL_HANDLE;
            }

            if (m_meshLayout != VK_NULL_HANDLE)
            {
                vkDestroyPipelineLayout(m_device, m_meshLayout, nullptr);
                m_meshLayout = VK_NULL_HANDLE;
            }
            if (m_meshPass != VK_NULL_HANDLE)
            {
                vkDestroyRenderPass(m_device, m_meshPass, nullptr);
                m_meshPass = VK_NULL_HANDLE;
            }
            if (m_meshDescriptorPool != VK_NULL_HANDLE)
            {
                vkDestroyDescriptorPool(m_device, m_meshDescriptorPool, nullptr);
                m_meshDescriptorPool = VK_NULL_HANDLE;
                m_meshDescriptorSets.fill(VK_NULL_HANDLE);
            }
            if (m_meshSetLayout != VK_NULL_HANDLE)
            {
                vkDestroyDescriptorSetLayout(m_device, m_meshSetLayout, nullptr);
                m_meshSetLayout = VK_NULL_HANDLE;
            }
            m_meshReady = false;
        }

        bool VulkanRenderer::createMeshTargets()
        {
            destroyMeshTargets();

            m_swapchainViews.resize(m_swapchainImages.size(), VK_NULL_HANDLE);
            for (size_t i = 0; i < m_swapchainImages.size(); ++i)
            {
                VkImageViewCreateInfo info{VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
                info.image = m_swapchainImages[i];
                info.viewType = VK_IMAGE_VIEW_TYPE_2D;
                info.format = m_swapchainFormat;
                info.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
                info.subresourceRange.levelCount = 1u;
                info.subresourceRange.layerCount = 1u;
                if (!check(vkCreateImageView(m_device, &info, nullptr, &m_swapchainViews[i]), "vkCreateImageView"))
                {
                    return false;
                }
            }

            // D32_SFLOAT rather than a packed 24-bit depth, because the GS's
            // own Z is 24-bit and the shader normalises it into a range near
            // zero: a float32 buffer has full mantissa there, a fixed-point
            // one would throw most of the range away.
            VkImageCreateInfo depthInfo{VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};
            depthInfo.imageType = VK_IMAGE_TYPE_2D;
            depthInfo.format = VK_FORMAT_D32_SFLOAT;
            depthInfo.extent = VkExtent3D{m_swapchainExtent.width, m_swapchainExtent.height, 1u};
            depthInfo.mipLevels = 1u;
            depthInfo.arrayLayers = 1u;
            depthInfo.samples = VK_SAMPLE_COUNT_1_BIT;
            depthInfo.tiling = VK_IMAGE_TILING_OPTIMAL;
            depthInfo.usage = VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT;
            depthInfo.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
            if (!check(vkCreateImage(m_device, &depthInfo, nullptr, &m_depthImage), "vkCreateImage(depth)"))
            {
                return false;
            }

            VkMemoryRequirements depthReq{};
            vkGetImageMemoryRequirements(m_device, m_depthImage, &depthReq);
            uint32_t depthType = 0u;
            if (!findMemoryType(depthReq.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, depthType))
            {
                return false;
            }
            VkMemoryAllocateInfo depthAlloc{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
            depthAlloc.allocationSize = depthReq.size;
            depthAlloc.memoryTypeIndex = depthType;
            if (!check(vkAllocateMemory(m_device, &depthAlloc, nullptr, &m_depthMemory), "vkAllocateMemory(depth)"))
            {
                return false;
            }
            vkBindImageMemory(m_device, m_depthImage, m_depthMemory, 0u);

            VkImageViewCreateInfo depthViewInfo{VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
            depthViewInfo.image = m_depthImage;
            depthViewInfo.viewType = VK_IMAGE_VIEW_TYPE_2D;
            depthViewInfo.format = VK_FORMAT_D32_SFLOAT;
            depthViewInfo.subresourceRange.aspectMask = VK_IMAGE_ASPECT_DEPTH_BIT;
            depthViewInfo.subresourceRange.levelCount = 1u;
            depthViewInfo.subresourceRange.layerCount = 1u;
            if (!check(vkCreateImageView(m_device, &depthViewInfo, nullptr, &m_depthView), "vkCreateImageView(depth)"))
            {
                return false;
            }

            m_meshFramebuffers.resize(m_swapchainImages.size(), VK_NULL_HANDLE);
            for (size_t i = 0; i < m_swapchainViews.size(); ++i)
            {
                const std::array<VkImageView, 2> views{m_swapchainViews[i], m_depthView};
                VkFramebufferCreateInfo info{VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO};
                info.renderPass = m_meshPass;
                info.attachmentCount = (uint32_t)views.size();
                info.pAttachments = views.data();
                info.width = m_swapchainExtent.width;
                info.height = m_swapchainExtent.height;
                info.layers = 1u;
                if (!check(vkCreateFramebuffer(m_device, &info, nullptr, &m_meshFramebuffers[i]),
                           "vkCreateFramebuffer"))
                {
                    return false;
                }
            }

            return true;
        }

        void VulkanRenderer::destroyMeshTargets()
        {
            for (VkFramebuffer &fb : m_meshFramebuffers)
            {
                if (fb != VK_NULL_HANDLE)
                {
                    vkDestroyFramebuffer(m_device, fb, nullptr);
                    fb = VK_NULL_HANDLE;
                }
            }
            m_meshFramebuffers.clear();

            for (VkImageView &view : m_swapchainViews)
            {
                if (view != VK_NULL_HANDLE)
                {
                    vkDestroyImageView(m_device, view, nullptr);
                    view = VK_NULL_HANDLE;
                }
            }
            m_swapchainViews.clear();

            if (m_depthView != VK_NULL_HANDLE)
            {
                vkDestroyImageView(m_device, m_depthView, nullptr);
                m_depthView = VK_NULL_HANDLE;
            }
            if (m_depthImage != VK_NULL_HANDLE)
            {
                vkDestroyImage(m_device, m_depthImage, nullptr);
                m_depthImage = VK_NULL_HANDLE;
            }
            if (m_depthMemory != VK_NULL_HANDLE)
            {
                vkFreeMemory(m_device, m_depthMemory, nullptr);
                m_depthMemory = VK_NULL_HANDLE;
            }
        }

        bool VulkanRenderer::ensureDrawBuffer(uint32_t frameIndex, VkDeviceSize size)
        {
            if (m_drawCapacities[frameIndex] >= size)
            {
                return true;
            }

            // Grown, not resized to fit, so a frame that gains a draw does not
            // reallocate. The draw count is stable to within a few per cent
            // across gameplay frames.
            VkDeviceSize capacity = std::max<VkDeviceSize>(size, 64u * sizeof(GpuDrawData));
            capacity += capacity / 2u;

            if (m_drawMapped[frameIndex] != nullptr)
            {
                vkUnmapMemory(m_device, m_drawMemories[frameIndex]);
                m_drawMapped[frameIndex] = nullptr;
            }
            if (m_drawBuffers[frameIndex] != VK_NULL_HANDLE)
            {
                vkDestroyBuffer(m_device, m_drawBuffers[frameIndex], nullptr);
                m_drawBuffers[frameIndex] = VK_NULL_HANDLE;
            }
            if (m_drawMemories[frameIndex] != VK_NULL_HANDLE)
            {
                vkFreeMemory(m_device, m_drawMemories[frameIndex], nullptr);
                m_drawMemories[frameIndex] = VK_NULL_HANDLE;
            }

            VkBufferCreateInfo bufferInfo{VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO};
            bufferInfo.size = capacity;
            bufferInfo.usage = VK_BUFFER_USAGE_STORAGE_BUFFER_BIT;
            bufferInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
            if (!check(vkCreateBuffer(m_device, &bufferInfo, nullptr, &m_drawBuffers[frameIndex]),
                       "vkCreateBuffer(draws)"))
            {
                return false;
            }

            VkMemoryRequirements requirements{};
            vkGetBufferMemoryRequirements(m_device, m_drawBuffers[frameIndex], &requirements);
            uint32_t typeIndex = 0u;
            if (!findMemoryType(requirements.memoryTypeBits,
                                VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT,
                                typeIndex))
            {
                return false;
            }

            VkMemoryAllocateInfo allocInfo{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
            allocInfo.allocationSize = requirements.size;
            allocInfo.memoryTypeIndex = typeIndex;
            if (!check(vkAllocateMemory(m_device, &allocInfo, nullptr, &m_drawMemories[frameIndex]),
                       "vkAllocateMemory(draws)"))
            {
                return false;
            }
            vkBindBufferMemory(m_device, m_drawBuffers[frameIndex], m_drawMemories[frameIndex], 0u);
            if (!check(vkMapMemory(m_device, m_drawMemories[frameIndex], 0u, capacity, 0u,
                                   &m_drawMapped[frameIndex]),
                       "vkMapMemory(draws)"))
            {
                return false;
            }
            m_drawCapacities[frameIndex] = capacity;

            VkDescriptorBufferInfo bufferDesc{};
            bufferDesc.buffer = m_drawBuffers[frameIndex];
            bufferDesc.offset = 0u;
            bufferDesc.range = capacity;

            VkWriteDescriptorSet write{VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
            write.dstSet = m_meshDescriptorSets[frameIndex];
            write.dstBinding = 0u;
            write.descriptorCount = 1u;
            write.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
            write.pBufferInfo = &bufferDesc;
            vkUpdateDescriptorSets(m_device, 1u, &write, 0u, nullptr);
            return true;
        }

        const MeshBuffers *VulkanRenderer::meshBuffers(uint32_t meshKey)
        {
            auto it = m_meshCache.find(meshKey);
            if (it != m_meshCache.end())
            {
                ++m_meshCacheHits;
                return it->second.indexCount != 0u ? &it->second : nullptr;
            }

            ++m_meshCacheMisses;

            const scene::Vertex *verts = nullptr;
            const uint16_t *indices = nullptr;
            uint32_t vertCount = 0u;
            uint32_t indexCount = 0u;
            if (!scene::geometry(meshKey, &verts, vertCount, &indices, indexCount) ||
                vertCount == 0u || indexCount == 0u)
            {
                // Cached as empty so a mesh with no usable geometry is looked
                // up once rather than every frame for the rest of the run.
                ++m_meshNoGeometry;
                m_meshCache.emplace(meshKey, MeshBuffers{});
                return nullptr;
            }

            // Host-visible and written once. On a discrete GPU this wants a
            // staging copy into device-local memory; on the unified memory
            // this is developed against there is nothing to copy to. Upload
            // happens once per mesh either way, so it is not the hot path.
            auto makeBuffer = [&](VkBufferUsageFlags usage, const void *data, VkDeviceSize size,
                                  VkBuffer &buffer, VkDeviceMemory &memory) -> bool {
                VkBufferCreateInfo bufferInfo{VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO};
                bufferInfo.size = size;
                bufferInfo.usage = usage;
                bufferInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
                if (!check(vkCreateBuffer(m_device, &bufferInfo, nullptr, &buffer), "vkCreateBuffer(mesh)"))
                {
                    return false;
                }
                VkMemoryRequirements requirements{};
                vkGetBufferMemoryRequirements(m_device, buffer, &requirements);
                uint32_t typeIndex = 0u;
                if (!findMemoryType(requirements.memoryTypeBits,
                                    VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT,
                                    typeIndex))
                {
                    return false;
                }
                VkMemoryAllocateInfo allocInfo{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
                allocInfo.allocationSize = requirements.size;
                allocInfo.memoryTypeIndex = typeIndex;
                if (!check(vkAllocateMemory(m_device, &allocInfo, nullptr, &memory), "vkAllocateMemory(mesh)"))
                {
                    return false;
                }
                vkBindBufferMemory(m_device, buffer, memory, 0u);
                void *mapped = nullptr;
                if (!check(vkMapMemory(m_device, memory, 0u, size, 0u, &mapped), "vkMapMemory(mesh)"))
                {
                    return false;
                }
                std::memcpy(mapped, data, (size_t)size);
                vkUnmapMemory(m_device, memory);
                return true;
            };

            MeshBuffers buffers;
            const VkDeviceSize vertexBytes = (VkDeviceSize)vertCount * sizeof(scene::Vertex);
            const VkDeviceSize indexBytes = (VkDeviceSize)indexCount * sizeof(uint16_t);
            if (!makeBuffer(VK_BUFFER_USAGE_VERTEX_BUFFER_BIT, verts, vertexBytes,
                            buffers.vertexBuffer, buffers.vertexMemory) ||
                !makeBuffer(VK_BUFFER_USAGE_INDEX_BUFFER_BIT, indices, indexBytes,
                            buffers.indexBuffer, buffers.indexMemory))
            {
                m_meshCache.emplace(meshKey, buffers);
                return nullptr;
            }
            buffers.indexCount = indexCount;

            auto inserted = m_meshCache.emplace(meshKey, buffers);
            return &inserted.first->second;
        }

        void VulkanRenderer::drawScene(VkCommandBuffer cmd, uint32_t imageIndex, VkRect2D viewportRect)
        {
            if (!m_meshReady || imageIndex >= m_meshFramebuffers.size())
            {
                return;
            }

            scene::Camera camera{};
            bool cameraValid = false;
            const scene::DrawView *draws = nullptr;
            uint32_t drawCount = 0u;
            uint64_t serial = 0ull;
            if (!scene::acquireFrame(camera, cameraValid, &draws, drawCount, serial))
            {
                return;
            }

            ++m_meshFrames;
            m_meshSerial = serial;

            // A frame with no camera cannot be transformed at all, so it is
            // counted and skipped rather than drawn through a stale one.
            if (!cameraValid)
            {
                ++m_meshNoCamera;
                return;
            }

            m_drawStaging.clear();
            m_drawStaging.reserve(drawCount);
            for (uint32_t i = 0u; i < drawCount; ++i)
            {
                const scene::DrawView &d = draws[i];
                GpuDrawData entry{};
                const uint32_t count = std::min<uint32_t>(d.matrixCount, 4u);
                for (uint32_t m = 0u; m < count; ++m)
                {
                    std::memcpy(entry.m[m], d.matrices + (size_t)m * 16u, 16u * sizeof(float));
                }
                entry.matrixCount = count;
                if (m_tint)
                {
                    // A cheap integer hash spread over the three channels,
                    // biased away from black so nothing tints to invisible.
                    uint32_t h = d.meshKey * 2654435761u;
                    h ^= h >> 15;
                    entry.color[0] = 0.25f + 0.75f * (float)((h >> 0) & 0xFFu) / 255.0f;
                    entry.color[1] = 0.25f + 0.75f * (float)((h >> 8) & 0xFFu) / 255.0f;
                    entry.color[2] = 0.25f + 0.75f * (float)((h >> 16) & 0xFFu) / 255.0f;
                    entry.color[3] = 1.0f;
                }
                else
                {
                    std::memcpy(entry.color, d.material.color, sizeof(entry.color));
                }
                m_drawStaging.push_back(entry);
            }

            const uint32_t frameIndex = m_frame % kFramesInFlight;
            if (m_drawStaging.empty() ||
                !ensureDrawBuffer(frameIndex, m_drawStaging.size() * sizeof(GpuDrawData)))
            {
                return;
            }
            std::memcpy(m_drawMapped[frameIndex], m_drawStaging.data(),
                        m_drawStaging.size() * sizeof(GpuDrawData));

            // Zero for GREATER, because the shader keeps the GS's sense of
            // depth: bigger is nearer, so the far plane is zero. LESS needs
            // the opposite clear or nothing passes at all, which would look
            // exactly like a broken transform.
            VkClearValue depthClear{};
            depthClear.depthStencil.depth = (m_depthMode == 2) ? 1.0f : 0.0f;

            VkRenderPassBeginInfo passBegin{VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO};
            passBegin.renderPass = m_meshPass;
            passBegin.framebuffer = m_meshFramebuffers[imageIndex];
            passBegin.renderArea.extent = m_swapchainExtent;
            // Attachment 0 is LOAD, so only the depth attachment needs a
            // clear value; it still has to be the second entry.
            VkClearValue clears[2]{};
            clears[1] = depthClear;
            passBegin.clearValueCount = 2u;
            passBegin.pClearValues = clears;
            vkCmdBeginRenderPass(cmd, &passBegin, VK_SUBPASS_CONTENTS_INLINE);

            // The same letterboxed rect the software picture is blitted into,
            // so the two land on top of each other and can be compared by
            // looking at them.
            VkViewport viewport{};
            viewport.x = (float)viewportRect.offset.x;
            viewport.y = (float)viewportRect.offset.y;
            viewport.width = (float)viewportRect.extent.width;
            viewport.height = (float)viewportRect.extent.height;
            viewport.minDepth = 0.0f;
            viewport.maxDepth = 1.0f;
            vkCmdSetViewport(cmd, 0u, 1u, &viewport);
            vkCmdSetScissor(cmd, 0u, 1u, &viewportRect);

            vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, m_meshLayout, 0u, 1u,
                                    &m_meshDescriptorSets[frameIndex], 0u, nullptr);

            MeshPush push{};
            std::memcpy(push.cam, camera.m, sizeof(push.cam));
            std::memcpy(push.scale, camera.scale, 3u * sizeof(float));
            std::memcpy(push.offset, camera.offset, 3u * sizeof(float));
            float ofx = 0.0f;
            float ofy = 0.0f;
            scene::gsOffset(ofx, ofy);
            // Half the source picture, not half the window: the transform
            // lands in the guest's framebuffer and the viewport scales that
            // to the letterbox.
            push.viewport[0] = (float)m_sourceWidth * 0.5f;
            push.viewport[1] = (float)m_sourceHeight * 0.5f;
            push.viewport[2] = ofx;
            push.viewport[3] = ofy;

            uint64_t tris = 0ull;
            uint64_t drawn = 0ull;
            const uint32_t firstDraw = std::min(m_drawFirst, drawCount);
            const uint32_t lastDraw = (m_drawLimit == 0u)
                                          ? drawCount
                                          : std::min(firstDraw + m_drawLimit, drawCount);
            // Bound lazily and only when it changes. Draws arrive grouped by
            // material because PsMat::Select binds once for a run of them, so
            // a frame with 534 draws rebinds a handful of times.
            VkPipeline bound = VK_NULL_HANDLE;
            for (uint32_t i = firstDraw; i < lastDraw; ++i)
            {
                const MeshBuffers *buffers = meshBuffers(draws[i].meshKey);
                if (buffers == nullptr)
                {
                    continue;
                }

                const scene::Material &mat = draws[i].material;
                if (m_skipAlphaTested && mat.alphaTest)
                {
                    ++m_meshSkippedAte;
                    continue;
                }
                PipelineKey key{};
                key.ztst = mat.ztst & 3u;
                key.depthTest = mat.depthTest ? 1u : 0u;
                key.depthWrite = mat.depthWrite ? 1u : 0u;
                key.blend = mat.blend ? 1u : 0u;
                VkPipeline pipeline = pipelineFor(key);
                if (pipeline == VK_NULL_HANDLE)
                {
                    continue;
                }
                if (pipeline != bound)
                {
                    vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline);
                    bound = pipeline;
                    ++m_pipelineBinds;
                }

                push.drawIndex = i;
                vkCmdPushConstants(cmd, m_meshLayout, VK_SHADER_STAGE_VERTEX_BIT, 0u, sizeof(push), &push);
                const VkDeviceSize offset = 0u;
                vkCmdBindVertexBuffers(cmd, 0u, 1u, &buffers->vertexBuffer, &offset);
                vkCmdBindIndexBuffer(cmd, buffers->indexBuffer, 0u, VK_INDEX_TYPE_UINT16);
                vkCmdDrawIndexed(cmd, buffers->indexCount, 1u, 0u, 0, 0u);
                tris += buffers->indexCount / 3u;
                ++drawn;
            }

            vkCmdEndRenderPass(cmd);

            m_meshDraws += drawn;
            m_meshTris += tris;

            if (m_meshLogEvery > 0 && (m_meshFrames % (uint64_t)m_meshLogEvery) == 0ull)
            {
                std::fprintf(stderr,
                             "[ghpc/vk/mesh] frames=%llu serial=%llu submitted=%u drawn=%llu tris=%llu "
                             "cached=%zu hits=%llu misses=%llu noGeom=%llu noCam=%llu "
                             "pipelines=%zu binds=%llu ofx=%.1f ofy=%.1f src=%ux%u\n",
                             (unsigned long long)m_meshFrames, (unsigned long long)serial,
                             drawCount, (unsigned long long)drawn, (unsigned long long)tris,
                             m_meshCache.size(), (unsigned long long)m_meshCacheHits,
                             (unsigned long long)m_meshCacheMisses,
                             (unsigned long long)m_meshNoGeometry, (unsigned long long)m_meshNoCamera,
                             m_pipelines.size(), (unsigned long long)m_pipelineBinds,
                             ofx, ofy, m_sourceWidth, m_sourceHeight);
            }
        }

        void VulkanRenderer::reportMesh()
        {
            if (m_meshFrames == 0ull)
            {
                return;
            }
            std::cout << "[ghpc/vk/mesh] frames=" << m_meshFrames
                      << " draws=" << m_meshDraws
                      << " tris=" << m_meshTris
                      << " meshes=" << m_meshCache.size()
                      << " hits=" << m_meshCacheHits
                      << " misses=" << m_meshCacheMisses
                      << " noGeometry=" << m_meshNoGeometry
                      << " noCamera=" << m_meshNoCamera
                      << " pipelines=" << m_pipelines.size()
                      << " pipelineBinds=" << m_pipelineBinds
                      << " skippedAte=" << m_meshSkippedAte << std::endl;
            m_meshFrames = 0ull;
        }

